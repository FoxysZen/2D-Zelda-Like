/**
 * @brief Identifies the type of event the trigger will do.
 */
enum TriggerEvent
{
    NONE,
    CHANGE_MAP,
    MSG_SIGN,
    MSG_NPC,
    TAKE_DMG,
    HEAL
};

/**
 * @brief Contains the all the needed data to create a trigger.
 */
struct TriggerData
{
    SDL_Rect area = {0, 0, 16, 16};
    TriggerEvent event = TriggerEvent::NONE;
    TriggerType type = TriggerType::ON_ENTER;
    std::string map = "test";
    std::string msg = "Default msg.";
    int amount = 1;

    bool oneShot = false;
    bool isActive = true;
};

/**
 * @brief Contains the info of a single object (Items or decorations).
 */
struct ObjectData
{
    uint8_t id = 0;
    SDL_Rect position { 0, 0, 0, 0 };

    bool enabled = true;

    TriggerData trigger = {};
};

